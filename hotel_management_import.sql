SET NAMES utf8mb4;
SET CHARACTER SET utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';

CREATE DATABASE IF NOT EXISTS `hotel_management`
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE `hotel_management`;

-- Xóa bảng cũ (thứ tự ngược FK)
DROP TABLE IF EXISTS `service_usage`;
DROP TABLE IF EXISTS `invoices`;
DROP TABLE IF EXISTS `bookings`;
DROP TABLE IF EXISTS `services`;
DROP TABLE IF EXISTS `rooms`;
DROP TABLE IF EXISTS `room_types`;
DROP TABLE IF EXISTS `users`;

-- ---------------------------------------------------------------------------
-- 1. users
-- ---------------------------------------------------------------------------
CREATE TABLE `users` (
  `id` int NOT NULL AUTO_INCREMENT,
  `create_at` datetime(6) NOT NULL,
  `email` varchar(100) NOT NULL,
  `full_name` varchar(100) NOT NULL,
  `password` varchar(255) NOT NULL,
  `phone` varchar(20) DEFAULT NULL,
  `role` enum('ADMIN','RECEPTIONIST','CUSTOMER') NOT NULL,
  `status` enum('ACTIVE','DELETED','INACTIVE','SUSPENDED') NOT NULL,
  `update_at` datetime(6) NOT NULL,
  `username` varchar(100) NOT NULL,
  `security_answer_hash` varchar(255) DEFAULT NULL,
  `security_question` varchar(255) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_users_email` (`email`),
  UNIQUE KEY `uk_users_username` (`username`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- 2. room_types
-- ---------------------------------------------------------------------------
CREATE TABLE `room_types` (
  `id` int NOT NULL AUTO_INCREMENT,
  `create_at` datetime(6) NOT NULL,
  `description` text,
  `name` varchar(100) NOT NULL,
  `update_at` datetime(6) NOT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- 3. rooms
-- ---------------------------------------------------------------------------
CREATE TABLE `rooms` (
  `id` int NOT NULL AUTO_INCREMENT,
  `capacity` int NOT NULL,
  `create_at` datetime(6) NOT NULL,
  `description` text,
  `img_folder` varchar(255) DEFAULT NULL,
  `price` int NOT NULL,
  `room_number` varchar(50) NOT NULL,
  `status` enum('AVAILABLE','MAINTENANCE','OCCUPIED','RESERVED','UNAVAILABLE') NOT NULL,
  `update_at` datetime(6) NOT NULL,
  `type_id` int NOT NULL,
  `hourly_price` int DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_rooms_room_number` (`room_number`),
  KEY `fk_rooms_type_id` (`type_id`),
  CONSTRAINT `fk_rooms_type_id` FOREIGN KEY (`type_id`) REFERENCES `room_types` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- 4. services
-- ---------------------------------------------------------------------------
CREATE TABLE `services` (
  `id` int NOT NULL AUTO_INCREMENT,
  `create_at` datetime(6) NOT NULL,
  `is_active` bit(1) NOT NULL DEFAULT b'1',
  `name` varchar(100) NOT NULL,
  `price` int NOT NULL,
  `unit` varchar(50) NOT NULL,
  `update_at` datetime(6) NOT NULL,
  `image_url` varchar(500) DEFAULT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- 5. bookings
-- ---------------------------------------------------------------------------
CREATE TABLE `bookings` (
  `id` int NOT NULL AUTO_INCREMENT,
  `check_in_at` datetime(6) NOT NULL,
  `check_out_at` datetime(6) NOT NULL,
  `create_at` datetime(6) NOT NULL,
  `note` text,
  `room_price` int NOT NULL,
  `status` enum('CANCELLED','CHECKED_IN','CHECKED_OUT','CONFIRMED','PENDING') NOT NULL,
  `total_price` int NOT NULL,
  `update_at` datetime(6) NOT NULL,
  `room_id` int NOT NULL,
  `user_id` int NOT NULL,
  PRIMARY KEY (`id`),
  KEY `fk_bookings_room_id` (`room_id`),
  KEY `fk_bookings_user_id` (`user_id`),
  CONSTRAINT `fk_bookings_user_id` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`),
  CONSTRAINT `fk_bookings_room_id` FOREIGN KEY (`room_id`) REFERENCES `rooms` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- 6. invoices
-- ---------------------------------------------------------------------------
CREATE TABLE `invoices` (
  `id` int NOT NULL AUTO_INCREMENT,
  `create_at` datetime(6) NOT NULL,
  `note` text,
  `paid_at` datetime(6) DEFAULT NULL,
  `pay_method` enum('BANK_TRANSFER','CASH') NOT NULL,
  `room_amount` int NOT NULL,
  `service_amount` int NOT NULL,
  `status` enum('CANCELLED','OVERDUE','PAID','PARTIALLY_PAID','PENDING') NOT NULL,
  `total_price` int NOT NULL,
  `update_at` datetime(6) NOT NULL,
  `booking_id` int NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_invoices_booking_id` (`booking_id`),
  CONSTRAINT `fk_invoices_booking_id` FOREIGN KEY (`booking_id`) REFERENCES `bookings` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- 7. service_usage
-- ---------------------------------------------------------------------------
CREATE TABLE `service_usage` (
  `id` int NOT NULL AUTO_INCREMENT,
  `quantity` int NOT NULL,
  `total_price` int NOT NULL,
  `unit_price` int NOT NULL,
  `use_at` datetime(6) NOT NULL,
  `booking_id` int NOT NULL,
  `service_id` int NOT NULL,
  PRIMARY KEY (`id`),
  KEY `fk_service_usage_booking_id` (`booking_id`),
  KEY `fk_service_usage_service_id` (`service_id`),
  CONSTRAINT `fk_service_usage_booking_id` FOREIGN KEY (`booking_id`) REFERENCES `bookings` (`id`),
  CONSTRAINT `fk_service_usage_service_id` FOREIGN KEY (`service_id`) REFERENCES `services` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

